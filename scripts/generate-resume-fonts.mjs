/**
 * Regenerates src/lib/resume-fonts.ts from src/assets/*.ttf.
 * The fonts are inlined as base64 so the resume PDF generator works on
 * runtimes without a filesystem (Cloudflare Workers).
 *
 * Usage: node scripts/generate-resume-fonts.mjs
 */
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const regular = readFileSync(path.join(root, "src/assets/NotoSansDevanagari-Regular.ttf"));
const bold = readFileSync(path.join(root, "src/assets/NotoSansDevanagari-Bold.ttf"));

const out = `// This file is auto-generated by scripts/generate-resume-fonts.mjs from src/assets/*.ttf.
// Do not edit by hand — edit the generator and re-run it to refresh the fonts.
// The base64 blobs let generateResumePdf() embed the Devanagari/Latin fonts on
// runtimes without a filesystem (Cloudflare Workers).

export const NOTO_SANS_DEVANAGARI_REGULAR_BASE64 =
  "${regular.toString("base64")}";

export const NOTO_SANS_DEVANAGARI_BOLD_BASE64 =
  "${bold.toString("base64")}";

export function base64ToBytes(base64: string): Uint8Array {
  return Uint8Array.from(atob(base64), (ch) => ch.charCodeAt(0));
}
`;

writeFileSync(path.join(root, "src/lib/resume-fonts.ts"), out);
console.log(`Wrote src/lib/resume-fonts.ts (regular ${regular.length} bytes, bold ${bold.length} bytes)`);
